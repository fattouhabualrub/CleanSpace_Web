#!/usr/bin/env node
/**
 * Generates sitemap.xml for every prerendered URL: 17 locales × 5 routes.
 *
 * Each <url> repeats the full xhtml:link alternate set, matching the hreflang
 * tags in the page head — Google cross-checks the two and ignores annotations
 * that disagree. <lastmod> comes from the last git commit that touched the
 * source, so it reflects real change rather than build time.
 *
 * Runs post-build and writes into the build output (and public/, so the
 * committed copy stays in step).
 *
 * Usage: node scripts/generate-sitemap.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Read a value out of the production environment file without importing TS. */
function fromEnvironment(key) {
  const src = readFileSync(join(ROOT, 'src/environments/environment.ts'), 'utf8');
  const m = src.match(new RegExp(`${key}:\\s*'([^']+)'`));
  if (!m) throw new Error(`environment.ts is missing ${key}`);
  return m[1];
}

/** Language codes, read from the single source in i18n.ts. */
function locales() {
  const src = readFileSync(join(ROOT, 'src/app/services/i18n.ts'), 'utf8');
  const block = src.slice(src.indexOf('LANGUAGES'), src.indexOf('@Injectable'));
  const codes = [...block.matchAll(/code:\s*'([^']+)'/g)].map((m) => m[1]);
  if (!codes.length) throw new Error('No language codes found in i18n.ts');
  return codes;
}

/** Route paths, read from PAGE_PATHS in app.routes.ts. */
function routes() {
  const src = readFileSync(join(ROOT, 'src/app/app.routes.ts'), 'utf8');
  const m = src.match(/PAGE_PATHS\s*=\s*\[([^\]]+)\]/);
  if (!m) throw new Error('PAGE_PATHS not found in app.routes.ts');
  return [...m[1].matchAll(/'([^']*)'/g)].map((x) => x[1]);
}

/** ISO date of the last commit touching src/ — the real "last modified". */
function lastmod() {
  try {
    const out = execFileSync('git', ['log', '-1', '--format=%cI', '--', 'src'], {
      cwd: ROOT,
      encoding: 'utf8',
    }).trim();
    return out ? out.slice(0, 10) : new Date().toISOString().slice(0, 10);
  } catch {
    return new Date().toISOString().slice(0, 10);
  }
}

const SITE = fromEnvironment('siteUrl');
const DEFAULT_LOCALE = fromEnvironment('defaultLocale');
const LOCALES = locales();
const ROUTES = routes();
const MODIFIED = lastmod();

const url = (locale, route) => (route ? `${SITE}/${locale}/${route}` : `${SITE}/${locale}`);

/** Home ranks above the rest; legal pages lowest. */
const priorityOf = (route) => (route === '' ? '1.0' : route === 'download' ? '0.8' : '0.5');
const changefreqOf = (route) => (route === '' ? 'weekly' : 'monthly');

const entries = [];
for (const route of ROUTES) {
  for (const locale of LOCALES) {
    const alternates = [
      ...LOCALES.map(
        (l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${url(l, route)}"/>`,
      ),
      `    <xhtml:link rel="alternate" hreflang="x-default" href="${url(DEFAULT_LOCALE, route)}"/>`,
    ].join('\n');

    entries.push(
      [
        '  <url>',
        `    <loc>${url(locale, route)}</loc>`,
        `    <lastmod>${MODIFIED}</lastmod>`,
        `    <changefreq>${changefreqOf(route)}</changefreq>`,
        `    <priority>${priorityOf(route)}</priority>`,
        alternates,
        '  </url>',
      ].join('\n'),
    );
  }
}

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- AUTO-GENERATED by scripts/generate-sitemap.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${entries.join('\n')}
</urlset>
`;

const targets = [
  join(ROOT, 'public/sitemap.xml'),
  join(ROOT, 'dist/cleanspace-landing/browser/sitemap.xml'),
];

for (const target of targets) {
  try {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, xml);
    console.log(`sitemap → ${target.replace(ROOT + '/', '')}`);
  } catch (err) {
    // The dist copy simply won't exist if this is run without a build.
    console.warn(`skipped ${target.replace(ROOT + '/', '')}: ${err.message}`);
  }
}

console.log(
  `${entries.length} URLs (${LOCALES.length} locales × ${ROUTES.length} routes), lastmod ${MODIFIED}`,
);
