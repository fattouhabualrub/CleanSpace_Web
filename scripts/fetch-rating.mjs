#!/usr/bin/env node
/**
 * Pulls CleanSpace's real App Store rating into src/app/core/seo/app-rating.ts.
 *
 * Apple keeps ratings per storefront, so this asks the public iTunes Lookup API
 * for each storefront where the app is likely to be rated and combines them
 * into one count-weighted average. The result feeds the AggregateRating in the
 * JSON-LD (what earns the star snippet in search results) and the visible
 * rating in the hero — Google requires the two to match, and both come from
 * this one file.
 *
 * Runs as `prebuild`. It never fails the build: if Apple can't be reached the
 * committed file is left as it was. The Lookup API allows roughly 20 calls a
 * minute, which is why the storefront list is short and the calls are paced.
 *
 * Usage: node scripts/fetch-rating.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/app/core/seo/app-rating.ts');

/** Arabic-speaking markets first (where the app is used most), then the large ones. */
const STOREFRONTS = [
  'jo', 'sa', 'ae', 'kw', 'qa', 'bh', 'om', 'eg', 'iq', 'lb', 'ma',
  'us', 'gb', 'ca', 'au', 'de', 'fr', 'tr',
];

function appStoreId() {
  const src = readFileSync(join(ROOT, 'src/environments/environment.ts'), 'utf8');
  const m = src.match(/appStoreId:\s*'(\d+)'/);
  if (!m) throw new Error('environment.ts is missing appStoreId');
  return m[1];
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function lookup(id, country) {
  const res = await fetch(`https://itunes.apple.com/lookup?id=${id}&country=${country}`, {
    signal: AbortSignal.timeout(8000),
  });
  if (!res.ok) throw new Error(`${country}: HTTP ${res.status}`);
  const app = (await res.json()).results?.[0];
  return { count: app?.userRatingCount ?? 0, value: app?.averageUserRating ?? 0 };
}

async function main() {
  const id = appStoreId();
  let count = 0;
  let weighted = 0;
  let answered = 0;
  for (const country of STOREFRONTS) {
    try {
      const r = await lookup(id, country);
      answered++;
      count += r.count;
      weighted += r.count * r.value;
    } catch (e) {
      console.warn(`rating: skipped ${e.message}`);
    }
    await sleep(250);
  }

  if (!answered) {
    console.warn('rating: App Store unreachable — keeping the committed app-rating.ts');
    return;
  }

  const value = count ? Math.round((weighted / count) * 10) / 10 : 0;
  const asOf = new Date().toISOString().slice(0, 10);
  writeFileSync(
    OUT,
    `// AUTO-GENERATED by scripts/fetch-rating.mjs (runs before every build) — do not edit by hand.
/** App Store user ratings, summed over ${STOREFRONTS.length} storefronts and averaged by count. */
export const APP_RATING = { value: ${value}, count: ${count}, asOf: '${asOf}' } as const;
`,
  );
  console.log(`rating: ${value} from ${count} ratings across ${answered} storefronts`);
}

main().catch((e) => console.warn(`rating: ${e.message} — keeping the committed app-rating.ts`));
